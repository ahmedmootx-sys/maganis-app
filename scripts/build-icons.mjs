import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const ICONS = [
  // Navigation & Shell
  'home', 'dumbbell', 'utensils', 'trending-up', 'settings', 'book-open', 'calendar',
  // Arrows & Direction
  'chevron-right', 'chevron-left', 'chevron-up', 'chevron-down',
  'arrow-right', 'arrow-left', 'arrow-up', 'arrow-down', 'arrow-up-right',
  'corner-up-left', 'chevron-first', 'chevron-last',
  // Common UI & Actions
  'x', 'check', 'check-circle', 'check-circle-2', 'check-check',
  'plus', 'minus', 'search', 'filter', 'sliders', 'sliders-horizontal',
  'more-vertical', 'more-horizontal', 'grip-vertical',
  'external-link', 'copy', 'share-2', 'info', 'alert-triangle', 'alert-circle',
  'help-circle', 'eye', 'eye-off', 'loader-2', 'trash-2', 'edit', 'edit-2', 'edit-3',
  'pencil', 'save', 'download', 'upload', 'folder', 'file', 'file-text',
  'refresh-cw', 'rotate-ccw', 'play', 'pause',
  // Fitness, Body & Nutrition
  'flame', 'activity', 'timer', 'clock', 'flag', 'trophy', 'award',
  'heart', 'shield', 'target', 'crosshair', 'zap', 'sparkles',
  'scale', 'user', 'sun', 'moon', 'dna', 'microscope',
  'apple', 'salad', 'carrot', 'pie-chart', 'bar-chart-2', 'layers', 'grid',
  'maximize-2', 'minimize-2', 'history', 'bell', 'lock', 'unlock',
  'smartphone', 'volume-2', 'volume-x'
];

const directionalIcons = [
  'chevron-right', 'chevron-left', 'arrow-right', 'arrow-left', 'arrow-up-right',
  'corner-up-left', 'undo', 'redo'
];

const iconsDir = path.join(rootDir, 'node_modules', 'lucide-static', 'icons');

const symbols = [];

for (const name of ICONS) {
  const filePath = path.join(iconsDir, `${name}.svg`);
  if (!fs.existsSync(filePath)) {
    console.error(`Icon not found: ${name} at ${filePath}`);
    process.exit(1);
  }
  const content = fs.readFileSync(filePath, 'utf8');
  // Extract inner SVG content
  const inner = content
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<svg[^>]*>/, '')
    .replace(/<\/svg>/, '')
    .trim();

  symbols.push(`      <symbol id="icon-${name}" viewBox="0 0 24 24">${inner}</symbol>`);
}

const spriteComponent = `/* Auto-generated by scripts/build-icons.mjs - DO NOT EDIT MANUALLY */
import React from 'react';

export const IconSprite: React.FC = () => {
  return (
    <svg
      id="maganis-icon-sprite"
      xmlns="http://www.w3.org/2000/svg"
      style={{ display: 'none', position: 'absolute', width: 0, height: 0, overflow: 'hidden' }}
      aria-hidden="true"
    >
      <defs>
${symbols.join('\n')}
      </defs>
    </svg>
  );
};
`;

const iconComponent = `/* Auto-generated by scripts/build-icons.mjs */
import React from 'react';

export type IconName =
${ICONS.map((i) => `  | '${i}'`).join('\n')};

export const DIRECTIONAL_ICONS = new Set<string>([
${directionalIcons.map((i) => `  '${i}',`).join('\n')}
]);

export interface IconProps extends React.SVGProps<SVGSVGElement> {
  name: IconName;
  size?: 16 | 18 | 20 | 24 | 28 | 32 | number;
  strokeWidth?: number;
  mirrorRtl?: boolean;
  className?: string;
}

export const Icon: React.FC<IconProps> = ({
  name,
  size = 20,
  strokeWidth = 1.75,
  mirrorRtl,
  className = '',
  style,
  ...props
}) => {
  const isDirectional = mirrorRtl ?? DIRECTIONAL_ICONS.has(name);
  const classes = [
    'maganis-icon',
    \`maganis-icon-\${name}\`,
    isDirectional ? 'maganis-icon--mirror-rtl' : '',
    className,
  ]
    .filter(Boolean)
    .join(' ');

  return (
    <svg
      className={classes}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden={props['aria-label'] ? undefined : true}
      style={{
        display: 'inline-block',
        verticalAlign: 'middle',
        flexShrink: 0,
        ...style,
      }}
      {...props}
    >
      <use href={\`#icon-\${name}\`} />
    </svg>
  );
};
`;

// Ensure src/ui exists
const uiDir = path.join(rootDir, 'src', 'ui');
if (!fs.existsSync(uiDir)) {
  fs.mkdirSync(uiDir, { recursive: true });
}

fs.writeFileSync(path.join(uiDir, 'IconSprite.tsx'), spriteComponent, 'utf8');
fs.writeFileSync(path.join(uiDir, 'Icon.tsx'), iconComponent, 'utf8');

console.log(`Successfully generated IconSprite.tsx and Icon.tsx with ${ICONS.length} icons.`);
