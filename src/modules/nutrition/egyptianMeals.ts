export function getMealsByGoal(goal: Goal): EgyptianMeal[] {
  return EGYPTIAN_MEALS.filter((m) => m.suitableGoals.includes(goal))
}

export function getMealsByCategory(
  category: 'breakfast' | 'lunch' | 'dinner' | 'snack',
): EgyptianMeal[] {
  return EGYPTIAN_MEALS.filter((m) => m.category === category)
}
